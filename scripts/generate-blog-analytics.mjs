import { writeFileSync } from "node:fs";
import { publicArticles, articlePath } from "../src/lib/blog/content.ts";

// Generated at build time: never put draft titles or paths in the client bundle.
const pages = Object.fromEntries([
  ["/blog", "Blog | Automatizza"],
  ["/blog/historico", "Archivo histórico | Automatizza"],
  ...publicArticles().map(article => [articlePath(article), article.meta_title]),
]);
writeFileSync(new URL("../src/lib/analytics/generated/blog-pages.ts", import.meta.url),
  `// Generated by scripts/generate-blog-analytics.mjs. Do not edit manually.\nexport const blogPageTitles: Record<string, string> = ${JSON.stringify(pages, null, 2)};\n`);
console.log(`Blog analytics: ${Object.keys(pages).length} public routes.`);
